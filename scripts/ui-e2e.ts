import { config } from "dotenv"; config({ path: ".env.local.wallets" });
import "../lib/server/ws-polyfill";
import { chromium } from "playwright";
import { NWCClient } from "@getalby/sdk/nwc";
const BASE = process.env.BASE ?? "http://localhost:3000";
const SHOTS = process.env.SHOTS ?? "/tmp";
const lud16 = new URL(process.env.NWC_CLIENT_URI!.replace("nostr+walletconnect://", "http://x/")).searchParams.get("lud16")!;
(async () => {
  const cli = new NWCClient({ nostrWalletConnectUrl: process.env.NWC_CLIENT_URI! });
  const b = await chromium.launch();
  const client = await b.newPage({ viewport: { width: 390, height: 844 } });
  await client.goto(`${BASE}/b/demo-braids`);
  await client.screenshot({ path: `${SHOTS}/1-booking.png`, fullPage: true });
  await client.locator('input[name="slot"]').first().check();
  await client.fill('input[type="email"]', lud16);
  await client.check('.agree input');
  await client.click("button.btn--block");
  await client.waitForSelector('a[href^="lightning:"]', { timeout: 30000 });
  const inv = (await client.getAttribute('a[href^="lightning:"]', "href"))!.slice(10);
  await client.screenshot({ path: `${SHOTS}/2-pay.png`, fullPage: true });
  cli.payInvoice({ invoice: inv }).catch(() => {});
  await client.waitForFunction(() => document.body.innerText.match(/Waiting for .* to accept/), null, { timeout: 30000 });
  await client.screenshot({ path: `${SHOTS}/3-held.png`, fullPage: true });
  console.log("held ✓");
  const prov = await b.newPage({ viewport: { width: 390, height: 844 } });
  await prov.goto(`${BASE}/login`);
  await prov.fill('input[autocomplete="username"]', "demo-braids");
  await prov.fill('input[type="password"]', "demo-braids-dashboard-key-0001");
  await prov.click("button.btn--lime");
  await prov.waitForURL(/dashboard/);
  await prov.screenshot({ path: `${SHOTS}/4-dash.png`, fullPage: true });
  await prov.click('.dash__row--held button.btn--lime');
  await prov.waitForSelector(".dash__row--accepted", { timeout: 30000 });
  console.log("accepted ✓");
  await client.waitForSelector(".pay__done", { timeout: 15000 });
  await client.click(".pay__done a");
  await client.waitForSelector(".verify--ok", { timeout: 15000 });
  const code = (await client.textContent(".checkin__code"))!.replace(/\s/g, "");
  await client.screenshot({ path: `${SHOTS}/5-receipt.png`, fullPage: true });
  console.log("receipt verified ✓ code", code);
  await prov.reload();
  await prov.fill('.dash__row--accepted input[inputmode="numeric"]', code);
  await prov.click('.dash__row--accepted .checkin-form button');
  await prov.waitForSelector(".dash__row--checked_in", { timeout: 15000 }).then(() => console.log("checked in ✓"), async () => console.log("check-in:", await prov.textContent(".dash__row--accepted .error")));
  await prov.screenshot({ path: `${SHOTS}/6-dash-after.png`, fullPage: true });
  await b.close(); cli.close(); process.exit(0);
})().catch((e) => { console.error(e); process.exit(1); });
