export const dictionaries: Record<Lang, Dict> = { en, fr };
export const getDict = (lang: string | undefined): Dict => dictionaries[lang === "fr" ? "fr" : "en"];
export function t(s: string, vars: Record<string, string | number> = {}) {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

